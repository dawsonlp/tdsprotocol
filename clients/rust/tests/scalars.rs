//! Shared Python edge values, checked independently of a network runtime.
use serde_json::{Value as Json, json};
use tds_client::{
    Record, SqlDate, SqlDateTime2, SqlDateTimeOffset, SqlDecimal, SqlTime, Value, tokens::Decoder,
};

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}
fn unhex(text: &str) -> Vec<u8> {
    text.as_bytes()
        .as_chunks::<2>()
        .0
        .iter()
        .map(|b| u8::from_str_radix(std::str::from_utf8(b).unwrap(), 16).unwrap())
        .collect()
}
fn view(value: Option<&Value>) -> Json {
    match value {
        Some(
            Value::NotDecrypted { .. } | Value::Encrypted(_) | Value::Variant(_) | Value::Vector(_),
        ) => panic!("variant has a separate corpus"),
        None => Json::Null,
        Some(Value::Integer(v)) => json!({"integer":v.to_string()}),
        Some(Value::Bit(v)) => json!({"bit":v}),
        Some(Value::Real(v)) => json!({"real":hex(&v.bits().to_le_bytes())}),
        Some(Value::Float(v)) => json!({"float":hex(&v.bits().to_le_bytes())}),
        Some(Value::Decimal(v)) => {
            json!({"decimal":[v.is_negative(),v.magnitude().to_string(),v.scale()]})
        }
        Some(Value::Money(v)) => json!({"money":v.0.to_string()}),
        Some(Value::Date(v)) => json!({"date":v.days()}),
        Some(Value::Time(v)) => json!({"time":v.ticks()}),
        Some(Value::DateTime2(v)) => json!({"datetime2":[u64::from(v.date.days()),v.time.ticks()]}),
        Some(Value::DateTimeOffset(v)) => {
            json!({"datetimeoffset":[i64::from(v.utc().date.days()),v.utc().time.ticks() as i64,i64::from(v.offset_minutes())]})
        }
        Some(Value::DateTime(v)) => json!({"datetime":[i64::from(v.days()),i64::from(v.ticks())]}),
        Some(Value::SmallDateTime(v)) => json!({"smalldatetime":[v.days(),v.minutes()]}),
        Some(Value::Unicode(v)) => json!({"unicode":v.0}),
        Some(Value::Text(v)) => json!({"text":[hex(&v.bytes),hex(&v.collation.0)]}),
        Some(Value::Binary(v)) => json!({"binary":hex(v)}),
        Some(Value::Guid(v)) => json!({"guid":hex(&v.0)}),
    }
}
fn metadata(info: &[u8]) -> Vec<u8> {
    let mut bytes = vec![0x81, 1, 0, 0, 0, 0, 0, 1, 0]; // one nullable column, user type 0
    bytes.extend(info);
    bytes.extend([1, b'v', 0]);
    bytes
}

#[test]
fn scalar_parameter_writers_match_the_python_wire_bytes() {
    let cases: Vec<Json> =
        serde_json::from_str(include_str!("fixtures/scalars/python.json")).unwrap();
    for case in cases {
        // Fixed read-only aliases canonicalize to nullable RPC forms. The
        // remaining corpus was generated by Python's parameter writers.
        if case["name"].as_str().unwrap().starts_with("fixed ") {
            continue;
        }
        let info = unhex(case["info"].as_str().unwrap());
        let payload = unhex(case["value"].as_str().unwrap());
        let mut decoder = Decoder::default();
        decoder.feed(&metadata(&info)).unwrap();
        let Some(Record::Columns(columns)) = decoder.next_record().unwrap() else {
            panic!("columns")
        };
        decoder
            .feed(&[vec![0xd1], payload.clone()].concat())
            .unwrap();
        let Some(Record::Row(row)) = decoder.next_record().unwrap() else {
            panic!("row")
        };
        let encoded = columns[0]
            .type_info
            .sql_type
            .encode_parameter(row[0].as_ref())
            .unwrap();
        assert_eq!(encoded, [info, payload].concat(), "{}", case["name"]);
    }
}

#[test]
fn python_scalar_limits_decode_across_fragments_and_both_null_forms() {
    let cases: Vec<Json> =
        serde_json::from_str(include_str!("fixtures/scalars/python.json")).unwrap();
    assert_eq!(cases.len(), 96);
    for case in cases {
        let header = metadata(&unhex(case["info"].as_str().unwrap()));
        let mut bytes = header.clone();
        bytes.push(0xd1);
        bytes.extend(unhex(case["value"].as_str().unwrap()));
        let mut cuts: Vec<_> = if bytes.len() <= 160 {
            (0..=bytes.len()).collect()
        } else {
            (0..=header.len() + 4).collect()
        };
        cuts.extend([bytes.len() / 2, bytes.len() - 1, bytes.len()]);
        for cut in cuts {
            let mut decoder = Decoder::default();
            let mut records = Vec::new();
            for part in [&bytes[..cut], &bytes[cut..]] {
                decoder.feed(part).unwrap();
                while let Some(record) = decoder.next_record().unwrap() {
                    records.push(record);
                }
            }
            assert!(decoder.is_empty());
            assert_eq!(records.len(), 2);
            let Record::Row(row) = &records[1] else {
                panic!("missing row")
            };
            assert_eq!(
                view(row[0].as_ref()),
                case["expected"],
                "{} at split {cut}",
                case["name"]
            );
        }
        // NBCROW omits each NULL's length and data, even for fixed-size types.
        let mut decoder = Decoder::default();
        decoder.feed(&header).unwrap();
        decoder.next_record().unwrap().unwrap();
        decoder.feed(&[0xd2, 1]).unwrap();
        assert_eq!(
            decoder.next_record().unwrap(),
            Some(Record::Row(vec![None]))
        );
        // Non-NULL NBCROW uses precisely the ordinary payload.
        if !case["expected"].is_null() {
            let mut bytes = vec![0xd2, 0];
            bytes.extend(unhex(case["value"].as_str().unwrap()));
            for byte in bytes {
                decoder.feed(&[byte]).unwrap();
            }
            let Some(Record::Row(row)) = decoder.next_record().unwrap() else {
                panic!("missing NBC row")
            };
            assert_eq!(view(row[0].as_ref()), case["expected"]);
        }
    }
}

#[test]
fn declared_integer_identity_is_independent_of_wire_code() {
    let mut infos = Vec::new();
    for code in [&[0x38][..], &[0x26, 4][..]] {
        let mut d = Decoder::default();
        d.feed(&metadata(code)).unwrap();
        let Some(Record::Columns(columns)) = d.next_record().unwrap() else {
            panic!("missing columns")
        };
        infos.push(columns[0].type_info.clone());
    }
    assert_eq!(infos[0].sql_type, infos[1].sql_type);
    assert_ne!(infos[0].code, infos[1].code);
}

#[test]
fn malformed_scalar_metadata_and_payloads_fail_without_committing_a_row() {
    for info in [
        &[0x26, 3][..],
        &[0x6a, 5, 0, 0],
        &[0x6a, 17, 38, 39],
        &[0x29, 8],
        &[0xe7, 1, 0],
        &[0xad, 0xff, 0xff], // fixed binary cannot be (max); varbinary can
    ] {
        let mut d = Decoder::default();
        d.feed(&metadata(info)).unwrap();
        assert!(d.next_record().is_err(), "{info:x?}");
    }
    for (info, value) in [
        (&[0x26, 4][..], &[2, 0, 0][..]),
        (&[0x6a, 5, 3, 0], &[5, 1, 0xe8, 3, 0, 0]), // magnitude 1000 exceeds precision 3
        (&[0x6a, 5, 9, 0], &[5, 2, 0, 0, 0, 0]),    // sign is neither positive nor negative
        (&[0x29, 0], &[3, 0x80, 0x51, 1]),          // 86400 seconds
        (&[0xa5, 1, 0], &[2, 0, 0, 0]),
        (&[0xe7, 2, 0, 9, 4, 0xd0, 0, 0x34], &[1, 0, 0]),
    ] {
        let mut d = Decoder::default();
        d.feed(&metadata(info)).unwrap();
        d.next_record().unwrap().unwrap();
        let mut row = vec![0xd1];
        row.extend(value);
        d.feed(&row).unwrap();
        assert!(d.next_record().is_err(), "{info:x?} {value:x?}");
    }
}

#[test]
fn exact_conversions_reject_rounding_and_calendar_overflow() {
    let negative_zero = SqlDecimal::new(true, 0, 38).unwrap();
    assert!(negative_zero.rescale_exact(0).unwrap().is_negative());
    assert_eq!(negative_zero.to_string(), format!("-0.{}", "0".repeat(38)));
    assert!(
        SqlDecimal::new(false, 123, 2)
            .unwrap()
            .rescale_exact(1)
            .is_err()
    );
    assert!(
        SqlDecimal::new(false, 10_u128.pow(38) - 1, 0)
            .unwrap()
            .rescale_exact(1)
            .is_err()
    );
    assert_eq!(
        SqlDecimal::new(false, 150, 2)
            .unwrap()
            .rescale_exact(1)
            .unwrap()
            .magnitude(),
        15
    );
    for (year, month, day) in [(1, 1, 1), (2000, 2, 29), (9999, 12, 31)] {
        assert_eq!(
            SqlDate::from_ymd(year, month, day).unwrap().to_ymd(),
            (year, month, day)
        );
    }
    assert!(SqlDate::from_ymd(1900, 2, 29).is_err());
    assert!(SqlTime::from_ticks(1).unwrap().at_scale(6).is_err());
    assert_eq!(SqlTime::from_ticks(10).unwrap().at_scale(6).unwrap(), 1);
    let utc = SqlDateTime2 {
        date: SqlDate::from_ymd(2026, 10, 17).unwrap(),
        time: SqlTime::from_ticks(1).unwrap(),
    };
    let local = SqlDateTimeOffset::new(utc, -60).unwrap().local().unwrap();
    assert_eq!(local.date.to_ymd(), (2026, 10, 16));
    assert_eq!(local.time.ticks(), 23 * 3600 * 10_000_000 + 1);
    let first = SqlDateTime2 {
        date: SqlDate::from_days(0).unwrap(),
        time: SqlTime::from_ticks(0).unwrap(),
    };
    assert!(SqlDateTimeOffset::new(first, -1).is_err());
}
