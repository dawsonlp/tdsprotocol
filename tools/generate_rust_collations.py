"""Freeze Python's SQL Server character mappings for the Rust client.

Run from the repository root with clients/python/.venv/bin/python. No server or
credentials are read: the reviewed server corrections already live in
clients/python/tds/collations.py. Regenerate both clients' server tables first if
their source evidence changes, then review this generated diff.

Each page has 256 lead flags, 256 little-endian u32 single characters, an
optional 65536-entry u32 pair table, then sorted 8-byte encoding records:
Unicode code point (u32), byte count (u8), two bytes, one reserved zero.
Pair sentinels mean retry the second byte (FFFFFFFF) or escape both (FFFFFFFE).
This avoids a platform codec dependency and preserves SQL's corrected mappings.
"""
import json
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "clients/python"))
from tds import collations, types  # noqa: E402

OUT = ROOT / "clients/rust/src/text"
OUT.mkdir(exist_ok=True)
blob = bytearray()
pages = []
golden = []


def digest(data):
    value = 0xCBF29CE484222325
    for b in data:
        value = ((value ^ b) * 0x100000001B3) & ((1 << 64) - 1)
    return f"{value:016x}"


numbers = sorted(set(collations.SORT_CODE_PAGES.values()) | set(collations.LOCALE_CODE_PAGES.values()))
for number in numbers:
    if not number:
        continue  # Unicode-only collation: no varchar codec.
    page = types.code_page(number)
    offset = len(blob)
    blob.extend(int(b in page.leads) for b in range(256))
    for b in range(256):
        blob.extend(struct.pack("<I", ord(page._single(bytes([b])))))
    if page.leads:
        for a in range(256):
            for b in range(256):
                pair = bytes([a, b])
                if a not in page.leads:
                    cp = 0xFFFFFFFF
                elif pair in page.reads:
                    cp = ord(page.reads[pair])
                elif pair in page.escaped:
                    cp = 0xFFFFFFFE
                else:
                    try:
                        text = pair.decode(page.python)
                    except UnicodeDecodeError:
                        text = ""
                    cp = ord(text) if len(text) == 1 else 0xFFFFFFFF
                blob.extend(struct.pack("<I", cp))
    encode_offset = len(blob)
    for cp in range(65536):
        try:
            data = page.encode(chr(cp))
        except types.ValueRefused:
            continue
        assert 1 <= len(data) <= 2
        blob.extend(struct.pack("<IB2sB", cp, len(data), data.ljust(2, b"\0"), 0))
    pages.append((number, offset, bool(page.leads), encode_offset, (len(blob) - encode_offset) // 8))
    # All byte pairs in sequence exercise malformed leads, cross-pair holding,
    # aliases, private-use characters and SQL-specific mappings together.
    data = bytes(b for a in range(256) for z in range(256) for b in (a, z))
    text = page.decode(data)
    golden.append(dict(page=number, units=len(text.encode("utf-16-le", "surrogatepass")) // 2,
                       decoded=digest(text.encode("utf-16-le", "surrogatepass")),
                       encoded=digest(page.encode(text))))

for data in [bytes(range(256)), b"a\xf0\x9f\xa6\x80\xed\xa0\x80\xe0\x80\xff\xf0\x9f"]:
    text = types.code_page(65001).decode(data)
    golden.append(dict(page=65001, raw=data.hex(), units=len(text.encode("utf-16-le", "surrogatepass")) // 2,
                       decoded=digest(text.encode("utf-16-le", "surrogatepass")),
                       encoded=digest(types.code_page(65001).encode(text))))

lines = ["// Generated by tools/generate_rust_collations.py; do not edit.",
         f"// SQL Server {collations.SERVER}; Python's reviewed SQL corrections and standard codecs.",
         'const DATA: &[u8] = include_bytes!("tables.bin");',
         "const PAGES: &[Page] = &["]
for number, offset, pairs, encode_offset, count in pages:
    lines.append(f"    Page {{ number: {number}, offset: {offset}, pairs: {str(pairs).lower()}, encode_offset: {encode_offset}, encode_len: {count} }},")
lines.append("];")
for name, mapping in [("SORT", collations.SORT_CODE_PAGES), ("LOCALE", collations.LOCALE_CODE_PAGES)]:
    lines.append(f"const {name}: &[(u32, u16)] = &[")
    lines.extend(f"    ({key}, {value})," for key, value in sorted(mapping.items()))
    lines.append("];")
(OUT / "tables.rs").write_text("\n".join(lines) + "\n")
subprocess.run(["rustfmt", "--edition", "2024", str(OUT / "tables.rs")], check=True)
(OUT / "tables.bin").write_bytes(blob)
fixture = ROOT / "clients/rust/tests/fixtures/collations"
fixture.mkdir(exist_ok=True)
(fixture / "python.json").write_text(json.dumps(golden, indent=2) + "\n")
print(f"{len(pages)} SQL code pages; {len(blob)} table bytes; {len(golden)} independent Python digests")
