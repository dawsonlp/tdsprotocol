    "<h3 id=\"porting-findings\">Porting findings</h3>",
    "<p><strong>Python checks task identity as well as serialization.</strong> The Python core compares caller identity on send/read. <code>test_serial_channels.py</code> checks wrong-owner use, explicit transfer, immediate busy/extra-channel refusal and cancel from another caller. A Rust mutex plus <code>&amp;mut self</code> would not automatically retain the same task restriction. The user selected a movable-ownership proposal for Rust (D-64), so the plan explicitly documents that semantic difference instead of claiming unchanged task permissions.</p>",
    "<p><strong>Scope exit is protocol work.</strong> <code>Response.__aexit__</code> awaits close, Attention and drain. <code>Response.__del__</code> only warns and leaves the channel busy. The pool tests distinguish successful awaited cleanup from abandonment: an unresolved exchange causes the whole connection to be discarded. A Rust destructor must not mark a channel idle just because the response value no longer exists.</p>",
    "<p><strong>Exact text is not always a Unicode string.</strong> Python uses <code>surrogatepass</code> for SQL's unpaired UTF-16 code units and escapes to retain noncanonical code-page bytes and invalid stored UTF-8. The Rust plan must establish lossless values and explicit conversions before claiming Python parity.</p>",
    "<p><strong>Numeric and time exactness is intentional.</strong> Python constructs decimal values from digits without precision-limited decimal arithmetic; custom time values retain 100 ns and 1/300-second ticks. Errors refuse rounding and name the call, parameter, row or column. Preserve those semantics and the distinction between a type's metadata and its value.</p>",
    "<p><strong>Response parity is semantic, not just matching rows.</strong> <code>test_response.py</code> compares captured records under whole, one-byte and randomized fragmentation, and with observation disabled. It checks messages, errors, completions, output ordinals and unknown/missing counts as well as row data. These are useful shared fixtures and Rust acceptance criteria.</p>",
    "<p><strong>Backpressure depends on consumption.</strong> Plain connections bound their inbox to eight packets. MARS returns credit as packets are consumed. Carry the policy into both the Rust core and shell; otherwise one can appear bounded while the other's queue grows. This review did not measure maximum retained memory or performance.</p>",
    "<p><strong>Source and design are not identical in every detail.</strong> The core's module description says it never uses a clock, but <code>connection/core.py</code> imports and calls <code>time.perf_counter()</code> for event and exchange timing. The Rust plan should supply time at the shell boundary. Also, <code>response.py</code> contains the asynchronous reading facade as well as the pure reader; the older building-plan layout table locates that facade in <code>shell.py</code>. Use actual source when mapping responsibilities. These observations do not invalidate the passing tests, and no Python refactor was performed.</p>",
    "<p><strong>Round trips can preserve a shared mistake.</strong> The existing Always Encrypted tests explicitly compare both write/read directions with .NET because the server cannot inspect encrypted plaintext. Retain independent evidence; do not count Rust/Python agreement or self round trips as sufficient cryptographic interoperability.</p>",
